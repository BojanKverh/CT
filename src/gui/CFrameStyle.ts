/**
 * Defines the geometric shape of a frame.
 */
export enum CFrameShape {
        /**
     * No frame.
     */
NoFrame,
        /**
     * Box.
     */
Box,
        /**
     * Panel.
     */
Panel,
        /**
     * Hline.
     */
HLine,
        /**
     * Vline.
     */
VLine
}

/**
 * Defines the visual shadow style of a frame.
 */
export enum CFrameShadow {
        /**
     * Plain.
     */
Plain,
        /**
     * Raised.
     */
Raised,
        /**
     * The control is pressed or sunken.
     */
Sunken
}
