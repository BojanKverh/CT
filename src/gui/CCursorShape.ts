/**
 * Defines cursor shapes supported by Canvas Toolkit.
 */
export enum CCursorShape {
		/**
	 * Standard arrow cursor.
	 */
Arrow,
		/**
	 * Split h.
	 */
SplitH,
		/**
	 * Split v.
	 */
SplitV,
		/**
	 * Pointing-hand cursor, typically used for links.
	 */
PointingHand,
		/**
	 * I-beam cursor used for text editing.
	 */
IBeam,
		/**
	 * Cross.
	 */
Cross,
		/**
	 * Size fdiag.
	 */
SizeFDiag,
        /**
     * Grab.
     */
Grab,
		/**
	 * Grabbing.
	 */
Grabbing,
		/**
	 * Disabled appearance.
	 */
Disabled
}