/**
 * Defines how a tool button displays its icon and text.
 */
export enum CToolButtonStyle {
        /**
     * Icon only.
     */
IconOnly,
        /**
     * Text only.
     */
TextOnly,
        /**
     * Text beside icon.
     */
TextBesideIcon,
        /**
     * Text under icon.
     */
TextUnderIcon
}
